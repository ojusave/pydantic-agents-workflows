"""Check real local HTTP and Workflows behavior using the synthetic worker.

Start the local simulation described in README.md, then run this module.
These checks never use provider keys and never access a hosted Render service.
"""

# Standard-library HTTP and test helpers keep the checks runnable after uv sync.
import json
import time
import unittest
from pathlib import Path
from urllib.request import Request, urlopen

BASE = "http://127.0.0.1:8040"
STATE = Path(".local")


def request(path, payload=None):
    """Send JSON to the local gateway and decode its reply."""
    body = None if payload is None else json.dumps(payload).encode()
    req = Request(BASE + path, data=body, headers={"Content-Type": "application/json"})
    with urlopen(req, timeout=20) as response:
        return json.load(response)


def run_question(question):
    """Submit a question and wait at most two minutes for its terminal result."""
    started = request(
        "/ask", {"question": question, "client_id": "native-integration-test"}
    )
    deadline = time.monotonic() + 120
    while time.monotonic() < deadline:
        result = request(
            f"/ask/{started['run_id']}?progress_token={started['progress_token']}"
        )
        if result["status"] in {"done", "failed"}:
            # Save local evidence, including the run ID needed to inspect tasks.
            evidence = {**started, **result}
            (STATE / f"{started['run_id']}.json").write_text(
                json.dumps(evidence, indent=2)
            )
            return evidence
        time.sleep(0.5)
    raise AssertionError(f"Local run exceeded two minutes: {started['run_id']}")


def model_events(since):
    """Read only callback evidence generated by this test, excluding older runs."""
    path = STATE / "synthetic-model-calls.jsonl"
    return [
        row
        for line in path.read_text().splitlines()
        if (row := json.loads(line))["time"] >= since
    ]


class NativeIntegrationTests(unittest.TestCase):
    """Exercise completion, retries, empty output, and permanent failure."""

    def test_complete_answer_uses_separate_model_workers(self):
        """A broad question must use all seven agents and preserve app output."""
        started = time.time()
        result = run_question("What web service deployment options does Render offer?")
        self.assertEqual(result["status"], "done", result)
        answer = result["result"]
        self.assertTrue(answer["answer"].startswith("SIMULATED LOCAL TEST"))
        self.assertEqual(len(answer["stages"]), 7)
        self.assertEqual(len(answer["claims"]), 2)
        self.assertEqual(len(answer["sources"]), 2)
        self.assertEqual(len(answer["evaluations"]), 2)
        self.assertTrue(answer["session_id"], "The completed answer must be saved")
        saved = request(
            f"/history/{answer['session_id']}?client_id=native-integration-test"
        )
        self.assertEqual(saved["answer"], answer["answer"])
        self.assertEqual(result["updates"][-1]["message"], "Answer ready")
        # Eight requests include two claims verified by the same named agent.
        events = [row for row in model_events(started) if row["event"] == "done"]
        self.assertEqual(len(events), 8, events)
        self.assertEqual(len({row["pid"] for row in events}), 8, events)
        self.assertEqual(sum(row["kind"] == "technical_accuracy" for row in events), 2)
        # All three judge intervals must overlap, proving real parallel waiting.
        judges = [
            row
            for row in model_events(started)
            if row["kind"] in {"accuracy_score", "technical_accuracy"}
        ]
        starts = [row["time"] for row in judges if row["event"] == "start"]
        ends = [row["time"] for row in judges if row["event"] == "done"]
        self.assertLess(max(starts), min(ends), judges)

    def test_retry_only_repeats_failed_model(self):
        """One injected answer failure must recover without repeating retrieval."""
        (STATE / "retry-once").unlink(missing_ok=True)
        started = time.time()
        result = run_question(
            "What web service options does Render offer? Retry probe."
        )
        self.assertEqual(result["status"], "done", result)
        events = model_events(started)
        self.assertEqual(sum(row["event"] == "injected_failure" for row in events), 1)
        self.assertEqual(
            sum(row["kind"] == "answer" and row["event"] == "start" for row in events),
            2,
        )
        self.assertEqual(
            sum(row["kind"] == "queries" and row["event"] == "start" for row in events),
            1,
        )

    def test_empty_claims_preserves_result_shape(self):
        """An answer with no factual claims must finish without missing cost fields."""
        result = run_question("What web service options exist? Empty claims probe.")
        self.assertEqual(result["status"], "done", result)
        self.assertEqual(result["result"]["claims"], [])
        stage = next(
            stage
            for stage in result["result"]["stages"]
            if stage["stage"] == "claims_verification"
        )
        self.assertEqual(stage["tokens_used"], 0)

    def test_permanent_failure_reaches_gateway(self):
        """After the model's three retries, the app must return a failed state."""
        started = time.time()
        result = run_question("What web service options exist? Failure probe.")
        self.assertEqual(result["status"], "failed", result)
        self.assertIn("Synthetic persistent failure", result["error"])
        events = model_events(started)
        self.assertEqual(sum(row["event"] == "injected_failure" for row in events), 4)
        self.assertEqual(
            sum(row["kind"] == "queries" and row["event"] == "start" for row in events),
            1,
        )


if __name__ == "__main__":
    # Verbose output names every passed scenario; any failure exits nonzero.
    unittest.main(verbosity=2)
